#!/usr/bin/env python3
"""Guard: the tracked Dreams import-name table must match its generator output.

`port/src/import_names_dreams.inc` is generated by the root `tools/gen_import_names.py` from
`notes/dreams-imports.json` (the static import analysis). Nothing else checks it, so a stale
table silently leaves implemented imports unresolved (missing symbol names).

Skips when the source analysis or the generator is absent (both live in the project root and
are not part of a `port`-only checkout):

    python3 -I tests/test_import_names.py
"""
import difflib
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
ROOT = PORT.parent
SOURCE = Path(os.environ.get("DREAMS_IMPORTS_JSON", ROOT / "notes" / "dreams-imports.json"))
GENERATOR = ROOT / "tools" / "gen_import_names.py"
TABLE = PORT / "src" / "import_names_dreams.inc"


class ImportNamesSync(unittest.TestCase):
    def test_generated_table_matches_tracked_file(self):
        if not SOURCE.is_file():
            self.skipTest(f"import analysis not found: {SOURCE}")
        if not GENERATOR.is_file():
            self.skipTest(f"generator not found: {GENERATOR}")
        if not TABLE.is_file():
            self.fail(f"tracked import-name table missing: {TABLE}")

        with tempfile.TemporaryDirectory() as tmp:
            output = Path(tmp) / "import_names_dreams.inc"
            result = subprocess.run(
                [sys.executable, "-I", str(GENERATOR), "--output", str(output)],
                cwd=ROOT,
                capture_output=True,
                text=True,
            )
            self.assertEqual(result.returncode, 0, result.stderr or result.stdout)
            self.assertTrue(output.is_file(), "generator did not write the table")

            expected = TABLE.read_bytes()
            actual = output.read_bytes()
            if actual != expected:
                diff = difflib.unified_diff(
                    expected.decode(errors="replace").splitlines(),
                    actual.decode(errors="replace").splitlines(),
                    fromfile=str(TABLE),
                    tofile="regenerated",
                    lineterm="",
                )
                self.fail(
                    "import_names_dreams.inc is stale; regenerate it with:\n"
                    "  python3 -I tools/gen_import_names.py\n\n"
                    + "\n".join(list(diff)[:40])
                )


if __name__ == "__main__":
    unittest.main(verbosity=2)
