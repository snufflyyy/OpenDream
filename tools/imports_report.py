#!/usr/bin/env python3
"""Render notes/dreams-imports.md tables from notes/dreams-imports.json (ps4_imports.py output).

Usage: imports_report.py IMPORTS_JSON EXTRACT_JSON HEADER_MD OUT_MD
HEADER_MD is hand-written narrative prepended verbatim.
"""
import json
import sys

# PS4 libraries with no bbport counterpart at all are grouped by theme for the summary.
THEMES = {
    "VR / PSVR": ["libSceHmd", "libSceHmdSetupDialog", "libSceVrTracker", "libSceVrServiceDialog"],
    "Move / Camera": ["libSceMove", "libSceCamera"],
    "Audio encode / 3D": ["libSceAudio3d", "libSceAt9Enc", "libSceM4aacEnc"],
    "Share / capture / streaming": ["libSceGameLiveStreaming", "libSceVideoRecording", "libSceScreenShot",
                                    "libSceShareUtility", "libSceContentExport", "libSceContentSearch"],
    "System dialogs / IME": ["libSceIme", "libSceErrorDialog", "libSceSigninDialog", "libSceNpFriendListDialog",
                             "libSceWebBrowserDialog"],
    "NP / online": ["libSceNpParty", "libSceNpUtility", "libSceOpenPsId", "libSceSystemServicePlatformPrivacy"],
    "Debug / misc": ["libSceCoredump", "libSceRandom", "libkernel_cpumode_platform", "libSceGnmWaitFreeSubmit",
                     "libSceRazorCpu", "ulobjmgr", "libSceLibcInternalExt"],
}


def cell_names(rows, pred, limit=None):
    names = [r["name"] or r["nid"] for r in rows if pred(r)]
    if limit and len(names) > limit:
        return ", ".join(names[:limit]) + ", ... (+%d)" % (len(names) - limit)
    return ", ".join(names)


def lib_table(imports, out):
    out.append("| Library | Funcs | bbport impl | of which stubs | online-only (bbnet20) | shadPS4 HLE | Missing in bbport |")
    out.append("|---|---:|---:|---:|---:|---:|---|")
    tot = dict(n=0, i=0, s=0, o=0, h=0)
    for lib, rows in sorted(imports.items(), key=lambda kv: (-sum(not r["implemented_in_bbport"] for r in kv[1]), kv[0])):
        n = len(rows)
        i = sum(r["implemented_in_bbport"] for r in rows)
        s = sum(":stub" in r["status"] for r in rows)
        o = sum("online_only" in r["status"] for r in rows)
        h = sum(bool(r["shadps4_hle"]) for r in rows)
        tot["n"] += n; tot["i"] += i; tot["s"] += s; tot["o"] += o; tot["h"] += h
        miss = cell_names(rows, lambda r: not r["implemented_in_bbport"], 12)
        if i == n and not miss:
            miss = "-"
        how = ""
        gm = [r for r in rows if r["status"].startswith("game_module")]
        if gm:
            how = " (via %s)" % gm[0]["status"].split(":", 1)[1]
        out.append("| %s%s | %d | %d | %d | %d | %d | %s |" % (lib, how, n, i, s, o, h, miss))
    out.append("| **total** | **%d** | **%d** | %d | %d | %d | |" % (tot["n"], tot["i"], tot["s"], tot["o"], tot["h"]))
    return tot


def main():
    d = json.load(open(sys.argv[1]))
    ex = json.load(open(sys.argv[2]))["report"]
    header = open(sys.argv[3]).read()
    out = [header.rstrip(), ""]
    out.append("## Coverage tables (generated by tools/imports_report.py)")
    out.append("")
    out.append("Status legend (from dreams-imports.json `notes.status_legend`):")
    for k, v in d["notes"]["status_legend"].items():
        out.append("- `%s`: %s" % (k, v))
    out.append("- *shadPS4 HLE* = NID has a `LIB_FUNCTION` in %s (many of those are stubs too)." % d["notes"]["shadps4_reference"])
    out.append("")
    for f, imports in d["imports"].items():
        meta = d["files"][f]
        out.append("### %s (%s, module `%s`)" % (f, meta["e_type"], meta["module_info"]["name"]))
        out.append("")
        lib_table(imports, out)
        out.append("")
    # libraries with zero coverage, eboot
    eb = d["imports"]["eboot.bin"]
    out.append("### Libraries the eboot imports that bbport has nothing for")
    out.append("")
    zero = {lib for lib, rows in eb.items() if not any(r["implemented_in_bbport"] for r in rows)}
    for theme, libs in THEMES.items():
        hit = [l for l in libs if l in zero]
        if hit:
            out.append("- **%s**: %s" % (theme, ", ".join("%s (%d)" % (l, len(eb[l])) for l in hit)))
    other = sorted(zero - {l for ls in THEMES.values() for l in ls})
    if other:
        out.append("- **Other**: " + ", ".join("%s (%d)" % (l, len(eb[l])) for l in other))
    out.append("")
    out.append("### Partially covered eboot libraries: full missing lists")
    out.append("")
    for lib, rows in sorted(eb.items()):
        if lib in zero:
            continue
        miss = [r for r in rows if not r["implemented_in_bbport"]]
        if not miss:
            continue
        out.append("- **%s** (%d/%d missing): %s" % (lib, len(miss), len(rows),
                                                     ", ".join("`%s`" % (r["name"] or r["nid"]) for r in miss)))
    out.append("")
    stubs = [(lib, r) for lib, rows in eb.items() for r in rows if ":stub" in r["status"]]
    if stubs:
        out.append("### eboot imports bbport only stubs (generic ok/fail handlers)")
        out.append("")
        out.append(", ".join("`%s`" % (r["name"] or r["nid"]) for lib, r in stubs))
        out.append("")
    needs = [(f, r) for f, imps in d["imports"].items() for rows in imps.values() for r in rows
             if "needs import_names" in r["status"]]
    if needs:
        out.append("### Implemented by name in bbport but NID missing from import_names*.inc")
        out.append("")
        out.append("bbport's `runtime_lookup` maps NID->name through `import_names*.inc`; these need a table "
                   "entry (trivial) before the existing implementation binds:")
        out.append("")
        out.append(", ".join(sorted({"`%s`" % r["name"] for f, r in needs})))
        out.append("")
    open(sys.argv[4], "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
