#!/usr/bin/env python3
"""Generate port/src/import_names_dreams.inc: NID -> symbol name for every import of Dreams'
eboot.bin and bundled prx (from notes/dreams-imports.json).

Why: bbport's runtime binds imports by *symbol name* (RuntimeExport tables) and finds the name
through NID tables (import_names.inc / import_names_extra.inc) that only list Bloodborne's imports.
Without a name, an import the runtime implements is still reported unresolved. NIDs are stable
hashes of the symbol name, so one table serves any game version (2.52, 2.64, ...).

Usage: python3 -I tools/gen_import_names.py   (re-run after regenerating dreams-imports.json)
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = json.loads((ROOT / 'notes/dreams-imports.json').read_text())
names = {}
for image, libs in data['imports'].items():
    for lib, entries in libs.items():
        for e in entries:
            if e.get('name'):
                names.setdefault(e['nid'], e['name'])
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--output', type=Path, default=ROOT / 'port/src/import_names_dreams.inc',
                help='write the generated table here (default: the tracked file)')
out = p.parse_args().output
lines = ['/* Generated by tools/gen_import_names.py from notes/dreams-imports.json: NID -> symbol name',
         ' * for every Dreams import (eboot + libc/Fios2/JobManager prx). Do not edit by hand. */']
lines += [f'{{"{nid}","{name}"}},' for nid, name in sorted(names.items(), key=lambda kv: kv[1])]
out.write_text('\n'.join(lines) + '\n')
print(f'{len(names)} names -> {out}')
